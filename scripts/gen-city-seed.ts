// apps/web/src/features/city/layout/navnagar.json -> supabase/seed/02_city.sql
// One source, so locate_point() / resolve_landmark() in SQL match the 3D world exactly.
import { readFileSync, writeFileSync } from 'node:fs';
import { arr, q } from './sql';

type Pt = [number, number];
type Names = { en: string; hi: string; mr: string };
type Layout = {
  river: { width: number; points: Pt[] };
  roads: { type: 'arterial' | 'main' | 'lane'; points: Pt[] }[];
  wards: { id: number; name: Names; polygon: Pt[] }[];
  landmarks: { name: Names; aliases?: string[]; x: number; z: number }[];
};

// Area centroid (shoelace).
function centroid(poly: Pt[]): Pt {
  let a = 0,
    cx = 0,
    cz = 0;
  poly.forEach(([x0, z0], i) => {
    const [x1, z1] = poly[(i + 1) % poly.length];
    const f = x0 * z1 - x1 * z0;
    a += f;
    cx += (x0 + x1) * f;
    cz += (z0 + z1) * f;
  });
  return [cx / (3 * a), cz / (3 * a)];
}

// Ray casting point-in-polygon.
function inside([x, z]: Pt, poly: Pt[]): boolean {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, zi] = poly[i];
    const [xj, zj] = poly[j];
    if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) hit = !hit;
  }
  return hit;
}

const city = JSON.parse(readFileSync('apps/web/src/features/city/layout/navnagar.json', 'utf8')) as Layout;
const out = [
  '-- GENERATED by `npm run gen:city` from apps/web/src/features/city/layout/navnagar.json. Do not edit.',
  '',
];

out.push('insert into wards (id, name_en, name_hi, name_mr, polygon, center_x, center_z) values');
out.push(
  city.wards
    .map((w) => {
      const [cx, cz] = centroid(w.polygon);
      return `  (${w.id}, ${q(w.name.en)}, ${q(w.name.hi)}, ${q(w.name.mr)}, ${q(JSON.stringify(w.polygon))}::jsonb, ${cx.toFixed(1)}, ${cz.toFixed(1)})`;
    })
    .join(',\n'),
);
out.push(
  'on conflict (id) do update set name_en = excluded.name_en, name_hi = excluded.name_hi, name_mr = excluded.name_mr,',
  '  polygon = excluded.polygon, center_x = excluded.center_x, center_z = excluded.center_z;',
  '',
);

// Landmark ids are positional and stable; the ward comes from the polygons, so they can't disagree.
out.push('insert into landmarks (id, ward_id, name_en, name_hi, name_mr, aliases, x, z) values');
out.push(
  city.landmarks
    .map((l, i) => {
      const ward = city.wards.find((w) => inside([l.x, l.z], w.polygon));
      if (!ward) throw new Error(`Landmark ${l.name.en} (${l.x}, ${l.z}) is outside every ward`);
      return `  (${i + 1}, ${ward.id}, ${q(l.name.en)}, ${q(l.name.hi)}, ${q(l.name.mr)}, ${arr(l.aliases)}, ${l.x}, ${l.z})`;
    })
    .join(',\n'),
);
out.push(
  'on conflict (id) do update set ward_id = excluded.ward_id, name_en = excluded.name_en, name_hi = excluded.name_hi,',
  '  name_mr = excluded.name_mr, aliases = excluded.aliases, x = excluded.x, z = excluded.z;',
  "select setval('landmarks_id_seq', (select max(id) from landmarks));",
  '',
);

// River and the roads that carry people over it, so locate_point() refuses open water but not a bridge.
const HALF = { arterial: 13, main: 8 }; // half road width (24 m, 14 m) + 1 m
const decks = city.roads.flatMap((r) => (r.type === 'lane' ? [] : [{ points: r.points, half: HALF[r.type] }]));
out.push(
  'insert into city_water (id, river, river_width, decks) values',
  `  (1, ${q(JSON.stringify(city.river.points))}::jsonb, ${city.river.width}, ${q(JSON.stringify(decks))}::jsonb)`,
  'on conflict (id) do update set river = excluded.river, river_width = excluded.river_width, decks = excluded.decks;',
  '',
);

writeFileSync('supabase/seed/02_city.sql', out.join('\n'));
console.log(`02_city.sql: ${city.wards.length} wards, ${city.landmarks.length} landmarks`);
