// config/workflow.yaml -> supabase/seed/01_workflow.sql
// Departments, categories (names/icon), initial SLA versions, workflow_transitions, app_settings.
// Idempotent: safe to re-run on every `db push --include-seed`.
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';
import { arr, q } from './sql';

type Names = { en: string; hi: string; mr: string };
type Transition = {
  action: string;
  from: string[];
  to: string;
  roles: string[];
  requires?: string[];
  guards?: string[];
  effects?: string[];
};
type Workflow = {
  departments: Record<string, Names>;
  categories: Record<string, Names & { department: string | null; hours: number; icon: string }>;
  transitions: Transition[];
  sla: { triage_hours: number; reopen_window_hours: number; auto_close_hours: number; warn_at: number };
};

const wf = parse(readFileSync('config/workflow.yaml', 'utf8')) as Workflow;
const out: string[] = ['-- GENERATED by `npm run gen:workflow` from config/workflow.yaml. Do not edit.', ''];

out.push('insert into departments (code, name_en, name_hi, name_mr) values');
out.push(
  Object.entries(wf.departments)
    .map(([code, n]) => `  (${q(code)}, ${q(n.en)}, ${q(n.hi)}, ${q(n.mr)})`)
    .join(',\n'),
);
out.push(
  'on conflict (code) do update set name_en = excluded.name_en, name_hi = excluded.name_hi, name_mr = excluded.name_mr;',
  '',
);

out.push('insert into categories (code, department_code, name_en, name_hi, name_mr, icon) values');
out.push(
  Object.entries(wf.categories)
    .map(([code, c]) => `  (${q(code)}, ${q(c.department)}, ${q(c.en)}, ${q(c.hi)}, ${q(c.mr)}, ${q(c.icon)})`)
    .join(',\n'),
);
out.push(
  'on conflict (code) do update set department_code = excluded.department_code, name_en = excluded.name_en,',
  '  name_hi = excluded.name_hi, name_mr = excluded.name_mr, icon = excluded.icon;',
  '',
);

// SLA policies are versioned: only the first version comes from YAML. Later changes go through
// update_sla_policy(), which inserts a new row.
out.push('insert into sla_policies (category_code, resolution_hours, effective_from, note)');
out.push("select v.code, v.hours, timestamptz '2000-01-01', 'initial (workflow.yaml)' from (values");
out.push(
  Object.entries(wf.categories)
    .map(([code, c]) => `  (${q(code)}, ${c.hours})`)
    .join(',\n'),
);
out.push(') v(code, hours) where not exists (select 1 from sla_policies p where p.category_code = v.code);', '');

out.push('delete from workflow_transitions;');
out.push(
  'insert into workflow_transitions (action, from_state, to_state, allowed_roles, requires, guards, effects) values',
);
out.push(
  wf.transitions
    .flatMap((t) =>
      t.from.map(
        (from) =>
          `  (${q(t.action)}, ${q(from)}, ${q(t.to)}, ${arr(t.roles)}, ${arr(t.requires)}, ${arr(t.guards)}, ${arr(t.effects)})`,
      ),
    )
    .join(',\n') + ';',
  '',
);

const s = wf.sla;
out.push(
  'insert into app_settings (id, triage_hours, reopen_window_hours, auto_close_hours, warn_at)',
  `values (1, ${s.triage_hours}, ${s.reopen_window_hours}, ${s.auto_close_hours}, ${s.warn_at})`,
  'on conflict (id) do update set triage_hours = excluded.triage_hours, reopen_window_hours = excluded.reopen_window_hours,',
  '  auto_close_hours = excluded.auto_close_hours, warn_at = excluded.warn_at;',
  '',
);

writeFileSync('supabase/seed/01_workflow.sql', out.join('\n'));
console.log(`01_workflow.sql: ${wf.transitions.length} transitions, ${Object.keys(wf.categories).length} categories`);
